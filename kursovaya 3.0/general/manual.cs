        private TabPage CreateHelpPage(string title, string[] lines, string note)
        {
            TabPage page = new TabPage(title);
            var panel = new TableLayoutPanel { Dock = DockStyle.Fill, ColumnCount = 1, RowCount = 3, Padding = new Padding(16), AutoScroll = true };
            panel.RowStyles.Add(new RowStyle(SizeType.AutoSize));
            panel.RowStyles.Add(new RowStyle(SizeType.AutoSize));
            panel.RowStyles.Add(new RowStyle(SizeType.Percent, 100));

            Label header = new Label { Text = title, AutoSize = true, Font = new Font("Segoe UI", 13F, FontStyle.Bold), ForeColor = Color.FromArgb(35, 45, 55), Margin = new Padding(0, 0, 0, 12) };
            panel.Controls.Add(header, 0, 0);

            FlowLayoutPanel content = new FlowLayoutPanel { Dock = DockStyle.Top, AutoSize = true, FlowDirection = FlowDirection.TopDown, WrapContents = false };
            for (int i = 0; i < lines.Length; i++)
            {
                Label item = new Label { Text = (i + 1).ToString() + ". " + lines[i], AutoSize = true, MaximumSize = new Size(880, 0), Margin = new Padding(0, 0, 0, 8) };
                content.Controls.Add(item);
            }
            panel.Controls.Add(content, 0, 1);

            Label noteLabel = new Label
            {
                Text = "Важно: " + note,
                AutoSize = true,
                MaximumSize = new Size(880, 0),
                BackColor = Color.FromArgb(255, 245, 204),
                ForeColor = Color.FromArgb(90, 70, 20),
                BorderStyle = BorderStyle.FixedSingle,
                Padding = new Padding(10),
                Margin = new Padding(0, 12, 0, 0),
                Font = new Font("Segoe UI", 9.5F, FontStyle.Bold)
            };
            panel.Controls.Add(noteLabel, 0, 2);
            page.Controls.Add(panel);
            return page;
        }
