        private int GetInitialHelpTabIndex(object sender)
        {
            Control control = sender as Control;
            if (control != null && control.Tag is int)
                return (int)control.Tag;

            if (tabControl1 == null || tabControl1.SelectedTab == null)
                return 0;
            if (tabControl1.SelectedTab == date) return 0;
            if (tabControl1.SelectedTab == first_level_decomposition) return 1;
            if (tabControl1.SelectedTab == second_level_decomposition) return 2;
            if (tabControl1.SelectedTab == third_level_decomposition) return 3;
            if (tabControl1.SelectedTab == fourth_level_decomposition) return 4;
            return 0;
        }

